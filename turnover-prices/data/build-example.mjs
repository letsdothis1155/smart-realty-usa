function offer(retailer, id, title, itemPrice, shipping) {
  const host = retailer === "ebay" ? "https://www.ebay.com/sch/i.html?_nkw=" : "https://www.walmart.com/search?q=";
  const q = encodeURIComponent(title.replace(/^Example\s+/i, ""));
  return {
    id,
    title,
    itemPrice,
    shipping,
    currency: "USD",
    condition: "New",
    url: host + q,
    checkedAt: CHECKED,
    example: true,
  };
}

function product(p) {
  return {
    id: p.id,
    category: p.category,
    name: p.name,
    summary: p.summary,
    unit: p.unit,
    qty: p.qty,
    defaultOn: !!p.defaultOn,
    retailers: {
      ebay: { offers: p.ebay },
      walmart: { offers: p.walmart },
    },
  };
}

