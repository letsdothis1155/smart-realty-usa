/**
 * Vendor-aware planning catalog. Products are dimensioned planning models that
 * link to the retailer's current search, not claims about live stock or price.
 * monetized stays false until a real affiliate network/tag exists.
 */

function vendorFor(row) {
  const group = String(row.group || row.category || "").toLowerCase();
  const query = encodeURIComponent(row.name || group || "furniture");
  if (/^(tv|speaker|gaming)$/.test(group)) {
    return { store: "Best Buy", vendor: "best-buy", productUrl: `https://www.bestbuy.com/site/searchpage.jsp?st=${query}` };
  }
  if (/^(sofa|sectional|table|rug|shelves|bed|dresser|bath)$/.test(group)) {
    return { store: "IKEA", vendor: "ikea", productUrl: `https://www.ikea.com/us/en/search/?q=${query}` };
  }
  if (group === "plant") {
    return { store: "The Home Depot", vendor: "home-depot", productUrl: `https://www.homedepot.com/s/${query}` };
  }
  return { store: "Wayfair", vendor: "wayfair", productUrl: `https://www.wayfair.com/keyword.php?keyword=${query}` };
}

function product(row) {
  const vendor = vendorFor(row);
  return {
    vendor: vendor.vendor,
    source: "retailer-planning",
    store: row.store || vendor.store,
    retailer: row.store || vendor.store,
    brand: row.brand || "Planning model",
    productUrl: row.productUrl || vendor.productUrl,
    affiliateUrl: row.affiliateUrl || "",
    affiliateNetwork: null,
    monetized: false,
    availability: "check_retailer",
    priceIsEstimate: true,
    modelSource: "procedural",
    glbUrl: "",
    ...row,
    ...(row.meshStyle === "tv" ? { wallMounted: true, snap: "wall" } : {}),
  };
}

